        <h1 class="h3 mb-4">Review &amp; Rating Guidelines</h1>
        <div class="content-area">
            <p class="lead">At Expostandzone.com, we value honest and constructive feedback to help exhibitors find reliable stand builders and improve service quality. To maintain transparency and credibility, we have established the following guidelines for submitting reviews and ratings.</p>

            <h2>1. General Guidelines</h2>
            <ul>
                <li><i class="fa fa-check-circle text-success"></i> <strong>Only Genuine Reviews</strong> – All reviews must be based on real experiences with the stand builder. Fake, misleading, or promotional reviews are strictly prohibited.</li>
                <li><i class="fa fa-check-circle text-success"></i> <strong>One Review per Experience</strong> – Users can submit only one review per project with a stand builder. Duplicate reviews will be removed.</li>
                <li><i class="fa fa-check-circle text-success"></i> <strong>Respectful &amp; Professional Language</strong> – No offensive, abusive, or defamatory language is allowed. Reviews should remain professional and constructive.</li>
                <li><i class="fa fa-check-circle text-success"></i> <strong>No Self-Promotion</strong> – Stand builders cannot review themselves or submit fake positive/negative reviews.</li>
                <li><i class="fa fa-check-circle text-success"></i> <strong>Verification Required</strong> – Users must verify their email before their review is published to ensure authenticity.</li>
            </ul>

            <h2>2. Rating System</h2>
            <p>Users can rate a stand builder based on the following four criteria, each rated from 1 to 5 stars:</p>
            <ul>
                <li><i class="fa fa-star text-warning"></i> <strong>Design Creativity &amp; Customization</strong></li>
                <li><i class="fa fa-star text-warning"></i> <strong>Quality of Workmanship &amp; Materials</strong></li>
                <li><i class="fa fa-star text-warning"></i> <strong>Project Management &amp; Timely Execution</strong></li>
                <li><i class="fa fa-star text-warning"></i> <strong>Cost Efficiency</strong></li>
            </ul>
            <p><strong>Final Rating Calculation:</strong> The overall rating is based on the average of all four criteria.</p>

            <h2>3. Review Submission Process</h2>
            <ol>
                <li>Submit Review – Users fill out a review form and rate the stand builder.</li>
                <li>Email Verification – A verification email is sent to the user's registered email.</li>
                <li>Review Approval – Once verified, the review is checked for compliance with our guidelines.</li>
                <li>Review Goes Live – The review is published and visible on the stand builder's profile.</li>
            </ol>

            <h2>4. Prohibited Content</h2>
            <ul>
                <li><i class="fa fa-times-circle text-danger"></i> <strong>Fake or Spam Reviews</strong></li>
                <li><i class="fa fa-times-circle text-danger"></i> <strong>Personal Attacks or Hate Speech</strong></li>
                <li><i class="fa fa-times-circle text-danger"></i> <strong>Inappropriate Language</strong></li>
                <li><i class="fa fa-times-circle text-danger"></i> <strong>Confidential Information</strong></li>
                <li><i class="fa fa-times-circle text-danger"></i> <strong>Irrelevant or Promotional Content</strong></li>
            </ul>

            <h2>5. Privacy &amp; Security</h2>
            <p>Your email is used for verification purposes. We do not share your personal information with stand builders beyond what you publish in the review.</p>

